import { AREA_COORDS, NIGERIA_LOCATIONS } from "@/constants/locations";
import { RECONFIRM_INTERVAL_DAYS } from "@/constants/marketplace";
import type {
  GeoPoint,
  Listing,
  ListingLocation,
  OtherCharge,
} from "@/lib/types";
import { LISTING_PHOTO_POOL } from "./images";

const MS_PER_DAY = 24 * 60 * 60 * 1000;
const THOUSAND = 1_000;

// Golden angle (137.5deg, in radians) — the classic constant for spreading
// points evenly around a circle without clustering. Used only to derive a
// fixed, deterministic per-listing coordinate offset from the listing's row
// index, so pins in the same area don't stack. Never Math.random() — the
// dataset must be byte-identical on every import.
const GOLDEN_ANGLE_RADIANS = 2.399963229728653;
const COORD_JITTER_DEG = 0.005;

// Exported so activity.ts can derive its own fixed timestamps from the same
// anchor instant — the whole dataset must be byte-identical on every import.
export const BASE_DATE = new Date("2026-07-29T09:00:00+01:00");
export { MS_PER_DAY };

function jitteredGeoPoint(area: string, index: number): GeoPoint {
  const base = AREA_COORDS[area];
  const angle = index * GOLDEN_ANGLE_RADIANS;
  return {
    lat: Number((base.lat + Math.cos(angle) * COORD_JITTER_DEG).toFixed(6)),
    lng: Number((base.lng + Math.sin(angle) * COORD_JITTER_DEG).toFixed(6)),
  };
}

function findAreaContext(area: string): { state: string; cityLga: string } {
  for (const state of NIGERIA_LOCATIONS) {
    for (const city of state.cities) {
      if (city.areas.some((a) => a.slug === area)) {
        return { state: state.slug, cityLga: city.slug };
      }
    }
  }
  throw new Error(`Unknown area slug: ${area}`);
}

function loc(area: string, street: string, index: number): ListingLocation {
  const { state, cityLga } = findAreaContext(area);
  return {
    state,
    cityLga,
    area,
    street,
    geoPoint: jitteredGeoPoint(area, index),
  };
}

function photosFor(index: number): string[] {
  const pool = LISTING_PHOTO_POOL[index % LISTING_PHOTO_POOL.length];
  return pool;
}

function roundToThousand(amount: number): number {
  return Math.round(amount / THOUSAND) * THOUSAND;
}

const AGENCY_FEE_RATE = 0.1;
const LEGAL_FEE_RATE = 0.05;
const CAUTION_DEPOSIT_RATE = 0.1;
const SALE_LEGAL_SURVEY_RATE = 0.02;
const SALE_AGENCY_FEE_RATE = 0.05;

function rentalCharges(price: number, serviceCharge?: number): OtherCharge[] {
  const charges: OtherCharge[] = [
    {
      label: "Agency fee",
      amount: roundToThousand(price * AGENCY_FEE_RATE),
      refundable: false,
    },
    {
      label: "Legal fee",
      amount: roundToThousand(price * LEGAL_FEE_RATE),
      refundable: false,
    },
    {
      label: "Caution deposit",
      amount: roundToThousand(price * CAUTION_DEPOSIT_RATE),
      refundable: true,
    },
  ];
  if (serviceCharge !== undefined) {
    charges.push({
      label: "Service charge",
      amount: roundToThousand(serviceCharge),
      refundable: false,
    });
  }
  return charges;
}

function saleCharges(price: number): OtherCharge[] {
  return [
    {
      label: "Legal & survey",
      amount: roundToThousand(price * SALE_LEGAL_SURVEY_RATE),
      refundable: false,
    },
    {
      label: "Agency fee",
      amount: roundToThousand(price * SALE_AGENCY_FEE_RATE),
      refundable: false,
    },
  ];
}

let seq = 0;

type ListingInput = Omit<
  Listing,
  "id" | "createdAt" | "lastConfirmedAvailableAt" | "reconfirmDueAt"
> & { daysOld: number; freshDaysAgo: number };

function listing(input: ListingInput): Listing {
  seq += 1;
  const { daysOld, freshDaysAgo, ...rest } = input;
  const createdAt = new Date(
    BASE_DATE.getTime() - daysOld * MS_PER_DAY,
  ).toISOString();
  const lastConfirmedAvailableAt = new Date(
    BASE_DATE.getTime() - freshDaysAgo * MS_PER_DAY,
  ).toISOString();
  const reconfirmDueAt = new Date(
    new Date(lastConfirmedAvailableAt).getTime() +
      RECONFIRM_INTERVAL_DAYS * MS_PER_DAY,
  ).toISOString();
  return {
    id: `listing-${seq}`,
    createdAt,
    lastConfirmedAvailableAt,
    reconfirmDueAt,
    ...rest,
  };
}

